// Build-time SEO for Apache (Namecheap) hosting.
//
// After `vite build` this writes, into dist/:
//   index.html, buy-cheese-online.html, products/<seo-slug>.html
//       copies of the app shell with that page's title, meta, canonical, OG
//       and JSON-LD hardcoded in <head> (visible in view-source / to bots)
//   200.html      plain app shell used as the SPA fallback for other routes
//   .htaccess     https+www, 301s for old URLs, prerendered pages, SPA fallback
//   sitemap.xml, robots.txt
import fs from "fs";
import path from "path";
import type { Plugin } from "vite";
import {
  HOME_SEO,
  SHOP_SEO,
  SITE_NAME,
  SITE_URL,
  allProductSeo,
  legacyProductSlugs,
  type PageSeo,
} from "./src/seo/seoConfig";

// Public, indexable routes without their own SEO entry (listed in the sitemap only).
const OTHER_PUBLIC_ROUTES = [
  "/about",
  "/contact",
  "/wholesale",
  "/process",
  "/faq",
  "/gifts",
  "/stories",
  "/portfolio/facility",
  "/portfolio/gallery",
  "/portfolio/testimonials",
  "/privacy-policy",
  "/terms-of-service",
  "/refund-policy",
  "/shipping-policy",
  "/return-policy",
];

const DISALLOWED = ["/admin", "/cart", "/checkout", "/user", "/orders", "/wishlist", "/thank-you", "/dummy"];

const escapeAttr = (value: string) =>
  value.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

const escapeRegex = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

function renderPage(shell: string, page: PageSeo): string {
  const url = `${SITE_URL}${page.path}`;
  const meta = (attr: "name" | "property", key: string, value?: string) =>
    value ? `  <meta ${attr}="${key}" content="${escapeAttr(value)}" />\n` : "";

  const head =
    `  <title>${escapeAttr(page.title)}</title>\n` +
    meta("name", "description", page.description) +
    meta("name", "keywords", page.keywords) +
    `  <link rel="canonical" href="${escapeAttr(url)}" />\n` +
    meta("property", "og:locale", "en_US") +
    meta("property", "og:type", "website") +
    meta("property", "og:site_name", SITE_NAME) +
    meta("property", "og:title", page.ogTitle || page.title) +
    meta("property", "og:description", page.ogDescription || page.description) +
    meta("property", "og:url", url) +
    (page.schema
      ? `  <script type="application/ld+json" data-seo="page-schema">${JSON.stringify(page.schema).replace(/</g, "\\u003c")}</script>\n`
      : "");

  // Drop the shell's default title/description/OG tags, then add this page's.
  const stripped = shell
    .replace(/\s*<title>[\s\S]*?<\/title>/, "")
    .replace(/\s*<meta\s+(?:name="(?:description|keywords)"|property="og:[^"]+")[\s\S]*?\/?>/g, "");
  return stripped.replace("</head>", `${head}</head>`);
}

function renderHtaccess(prerenderedPaths: string[]): string {
  const legacy = Object.entries(legacyProductSlugs())
    .map(([oldSlug, seoSlug]) => `  RewriteRule ^products/${escapeRegex(oldSlug)}/?$ /products/${seoSlug} [R=301,L]`)
    .join("\n");

  return `# Generated by vite-plugin-seo.ts on build - edit that file, not this one.
Options -MultiViews
DirectoryIndex index.html

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase /

  # Force https://www. (matches the canonical URLs)
  RewriteCond %{HTTPS} off [OR]
  RewriteCond %{HTTP_HOST} !^www\\. [NC]
  RewriteCond %{HTTP_HOST} ^(?:www\\.)?(.+)$ [NC]
  RewriteRule ^ https://www.%1%{REQUEST_URI} [R=301,L]

  # Old URLs -> SEO URLs (query strings are kept)
  RewriteRule ^shop/?$ /buy-cheese-online [R=301,L]
  RewriteRule ^privacy/?$ /privacy-policy [R=301,L]
  RewriteRule ^terms/?$ /terms-of-service [R=301,L]
  RewriteRule ^return/?$ /return-policy [R=301,L]
${legacy}

  # Prerendered SEO pages (${prerenderedPaths.length}): /buy-cheese-online -> /buy-cheese-online.html
  RewriteCond %{DOCUMENT_ROOT}/$1.html -f
  RewriteRule ^(.+?)/?$ /$1.html [L]

  # Everything else is handled by the React app
  RewriteRule ^(index|200)\\.html$ - [L]
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_FILENAME} !-d
  RewriteCond %{REQUEST_FILENAME} !-l
  RewriteRule . /200.html [L]
</IfModule>
`;
}

function renderSitemap(paths: string[]): string {
  const lastmod = new Date().toISOString().slice(0, 10);
  const urls = paths
    .map((p) => `  <url>\n    <loc>${SITE_URL}${p}</loc>\n    <lastmod>${lastmod}</lastmod>\n  </url>`)
    .join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`;
}

function renderRobots(): string {
  return `User-agent: *\nAllow: /\n${DISALLOWED.map((p) => `Disallow: ${p}`).join("\n")}\n\nSitemap: ${SITE_URL}/sitemap.xml\n`;
}

export default function seoPrerender(): Plugin {
  let outDir = "dist";
  return {
    name: "seo-prerender",
    apply: "build",
    configResolved(config) {
      outDir = path.resolve(config.root, config.build.outDir);
    },
    closeBundle() {
      const shellPath = path.join(outDir, "index.html");
      const shell = fs.readFileSync(shellPath, "utf8");
      fs.writeFileSync(path.join(outDir, "200.html"), shell);

      const pages: PageSeo[] = [HOME_SEO, SHOP_SEO, ...allProductSeo()];
      for (const page of pages) {
        const file = page.path === "/" ? "index.html" : `${page.path.slice(1)}.html`;
        const target = path.join(outDir, file);
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.writeFileSync(target, renderPage(shell, page));
      }

      const pagePaths = pages.map((p) => p.path);
      fs.writeFileSync(path.join(outDir, ".htaccess"), renderHtaccess(pagePaths.filter((p) => p !== "/")));
      fs.writeFileSync(path.join(outDir, "sitemap.xml"), renderSitemap([...pagePaths, ...OTHER_PUBLIC_ROUTES]));
      fs.writeFileSync(path.join(outDir, "robots.txt"), renderRobots());
      console.log(`\n[seo-prerender] ${pages.length} prerendered pages, .htaccess, sitemap.xml, robots.txt`);
    },
  };
}
